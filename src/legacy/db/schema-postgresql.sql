-- Additive PostgreSQL equivalent of schema.sql, schema-foundation.sql,
-- and the profile columns currently applied by migrate-foundation.ts.

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE IF NOT EXISTS nonprofits (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
