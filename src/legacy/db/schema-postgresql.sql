  city VARCHAR(100),
  state VARCHAR(50),
  zip VARCHAR(20),
  verification_status VARCHAR(20) NOT NULL DEFAULT 'unclaimed'
    CHECK (verification_status IN ('unclaimed', 'claimed', 'verified', 'needs_review', 'archived')),
  claim_status VARCHAR(20) NOT NULL DEFAULT 'unclaimed'
    CHECK (claim_status IN ('unclaimed', 'claimed', 'verified', 'needs_review', 'archived')),
  facebook_url VARCHAR(512),
  instagram_url VARCHAR(512),
  linkedin_url VARCHAR(512),
  tiktok_url VARCHAR(512),
  youtube_url VARCHAR(512),
