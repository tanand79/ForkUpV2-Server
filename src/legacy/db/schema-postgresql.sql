    FOREIGN KEY (nonprofit_id) REFERENCES nonprofits(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_campaigns_nonprofit_id ON campaigns(nonprofit_id);
CREATE INDEX IF NOT EXISTS idx_campaigns_status ON campaigns(campaign_status);

