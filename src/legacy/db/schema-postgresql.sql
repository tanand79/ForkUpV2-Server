CREATE TABLE IF NOT EXISTS campaigns (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(255) NOT NULL UNIQUE,
  nonprofit_id INTEGER NOT NULL,
  campaign_name VARCHAR(255) NOT NULL,
  campaign_story TEXT NOT NULL,
  campaign_goal INTEGER NOT NULL DEFAULT 0,
  campaign_start_date DATE,
  campaign_end_date DATE,
  campaign_status VARCHAR(30) NOT NULL DEFAULT 'draft'
    CHECK (campaign_status IN ('draft', 'in_review', 'invitation_phase', 'ready_to_launch', 'live', 'closed', 'settlement')),
  cover_image_url VARCHAR(2048) NOT NULL,
  -- Additive: optional YouTube watch/shorts URL for public hero (video first when set)
  featured_youtube_url VARCHAR(512),
  logo_url VARCHAR(512),
  raised INTEGER NOT NULL DEFAULT 0,
  supporters_going INTEGER NOT NULL DEFAULT 0,
  expected_guests INTEGER NOT NULL DEFAULT 0,
  verified_visits INTEGER NOT NULL DEFAULT 0,
  top_event BOOLEAN NOT NULL DEFAULT FALSE,
  terms_accepted BOOLEAN NOT NULL DEFAULT FALSE,
  terms_accepted_at TIMESTAMP,
  invitation_deadline DATE,
  -- Nick V2 Layer 2: Guest Bartending single event date + business timing / review gates
  event_date DATE,
  business_timing_status VARCHAR(40) NOT NULL DEFAULT 'ok'
    CHECK (business_timing_status IN (
      'ok',
      'needs_forkup_review',
      'limited_promotion_window',
      'tight_timeline',
      'too_soon'
    )),
  forkup_review_status VARCHAR(30) NOT NULL DEFAULT 'none'
    CHECK (forkup_review_status IN ('none', 'pending', 'approved', 'denied', 'changes_requested')),
  forkup_review_reason TEXT,
  forkup_review_requested_at TIMESTAMP,
  -- Timeline Check: organizer already has a business/venue confirmed (8–20 day band)
  confirmed_business_name VARCHAR(255),
  confirmed_contact_name VARCHAR(255),
  confirmed_contact_email VARCHAR(255),
  confirmed_method VARCHAR(30)
    CHECK (confirmed_method IS NULL OR confirmed_method IN ('email', 'phone', 'in_person')),
  confirmed_status VARCHAR(80),
  confirmed_notes TEXT,
  business_confirmed_at TIMESTAMP,
  created_by_user_id INTEGER,
  -- Settlement engine (ported from ForkUpSettlementEngine): grace + close + freeze
  settlement_grace_days INTEGER NOT NULL DEFAULT 7,
  settlement_closed_at TIMESTAMP,
  settlement_frozen_at TIMESTAMP,
  adjustment_window_end TIMESTAMP,
  settlement_closed_by VARCHAR(100),
  -- Settlement parity with old engine: NULL fees = platform defaults (15 / 2.9 / 0.30)
  platform_fee_percent DECIMAL(6,2),
  card_fee_percent DECIMAL(6,3),
  card_fee_fixed DECIMAL(10,2),
  bartender_tips DECIMAL(12,2) NOT NULL DEFAULT 0,
  silent_auction DECIMAL(12,2) NOT NULL DEFAULT 0,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_campaigns_nonprofit
    FOREIGN KEY (nonprofit_id) REFERENCES nonprofits(id) ON DELETE RESTRICT
);

