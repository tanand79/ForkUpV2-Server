  campaign_start_date DATE,
  campaign_end_date DATE,
  campaign_status VARCHAR(30) NOT NULL DEFAULT 'draft'
    CHECK (campaign_status IN ('draft', 'invitation_phase', 'ready_to_launch', 'live', 'closed', 'settlement')),
